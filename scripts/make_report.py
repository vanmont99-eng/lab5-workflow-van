"""Summary report (figure + markdown text) from the combined table.

Usage:
    python scripts/make_report.py --input results/combined_table.tsv \
        --figure results/summary_figure.png --report results/report.md
"""
import argparse
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

p = argparse.ArgumentParser()
p.add_argument("--input", required=True)
p.add_argument("--figure", required=True)
p.add_argument("--report", required=True)
a = p.parse_args()

df = pd.read_csv(a.input, sep="\t", keep_default_na=False, na_values=["NA"])
GENES = ["TP53", "KRAS", "EGFR", "STK11", "KEAP1"]

# ---- numbers for the text ----
n = len(df)
sites = df["enrollment_site"].value_counts().sort_index()
sex_counts = df["sex_sample"].value_counts()
glu = df.groupby("enrollment_site")["glucose_mg_dl"].median()
glu_flagged = df["glucose_flag"].notna().sum()
mmol_suspect = df["glucose_flag"].fillna("").str.contains("not converted").sum()
dob_inferred = df["dob_flag"].fillna("").str.contains("2-digit").sum()
pct_mut = {g: 100 * (df[f"{g}_count"] > 0).mean() for g in GENES}
stage_missing = df["stage"].isna().sum()
missing = df.isna().sum()
missing = missing[missing > 0]

# ---- figure ----
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(9, 3.6))
order = list(sites.index)
ax1.boxplot([df.loc[df.enrollment_site == s, "glucose_mg_dl"] for s in order])
ax1.set_xticks(range(1, len(order) + 1), [f"Site {s}" for s in order])
ax1.set_ylabel("Glucose (mg/dL)")
ax1.set_title("Lab 3 side: glucose by enrollment site")

ax2.bar(GENES, [pct_mut[g] for g in GENES], color="#1C7293")
ax2.set_ylabel("% of linked patients")
ax2.set_title("Lab 4 side: any protein-altering mutation")
fig.suptitle(f"Combined table, n = {n} (synthetic sample-patient linkage)", fontsize=10)
fig.tight_layout()
Path(a.figure).parent.mkdir(parents=True, exist_ok=True)
fig.savefig(a.figure, dpi=150)

# ---- text ----
lines = [
    "# Lab 5 summary report",
    "",
    "Generated by `scripts/make_report.py` from `results/combined_table.tsv`. "
    "Rerun the pipeline and this file is rebuilt.",
    "",
    "> **The sample-to-patient link is made up.** `messy_samples.csv` and `cohort.db` "
    "share no ID, so `scripts/make_crosswalk.py` pairs each sample with a random "
    "TCGA patient of the same sex. Nothing below that compares the two sides "
    "means anything biologically. This report describes the table, it doesn't "
    "make claims about patients.",
    "",
    f"![summary figure]({Path(a.figure).name})",
    "",
    "## What's in the table",
    "",
    f"- **{n} rows**, one per cleaned sample, each linked to one TCGA patient",
    f"- **{df.shape[1]} columns**: Lab 3 fields (dob, sex, site, glucose + flags), "
    "the crosswalk, and Lab 4 features (age, stage, tissue source site, TMB, 5 gene counts)",
    "- Samples per enrollment site: "
    + ", ".join(f"{s} = {c}" for s, c in sites.items()),
    "- Sample sex: "
    + ", ".join(f"{s} = {c}" for s, c in sex_counts.items())
    + " (Unknown-sex samples were linked to a patient of either sex)",
    "",
    "## Lab 3 side",
    "",
    "- Median glucose by site: "
    + ", ".join(f"{s} = {v:.1f} mg/dL" for s, v in glu.items()),
    f"- {glu_flagged} glucose values carry a flag. {mmol_suspect} were labeled mmol/L "
    "but the numbers only make sense as mg/dL, so they were kept as-is, not multiplied by 18.",
    f"- {dob_inferred} dates of birth had 2-digit years and the century was inferred.",
    "",
    "## Lab 4 side",
    "",
    "- % of linked patients with any protein-altering mutation: "
    + ", ".join(f"{g} {v:.0f}%" for g, v in pct_mut.items()),
    f"- {stage_missing} linked patients have no stage recorded in cohort.db.",
    "",
    "## Missing values",
    "",
]
if len(missing):
    lines += [f"- `{c}`: {v}" for c, v in missing.items()]
else:
    lines += ["- none"]
lines += [
    "",
    "`dob_flag`, `glucose_flag` and `notes` are mostly empty on purpose: "
    "blank means nothing needed flagging.",
    "",
]

Path(a.report).write_text("\n".join(lines))
print(f"wrote {a.figure} and {a.report}")
